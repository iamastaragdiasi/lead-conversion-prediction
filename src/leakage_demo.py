# Controlled leakage experiment + single-feature leakage screen.
# Uses the TRAINING split only. The test set is never touched.
import numpy as np
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import StratifiedKFold, cross_val_score
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

import review_utils as ru

LEAKY = "invoice_generated"
LEAK_NOISE = 0.03          # leaky column disagrees with the target for 3% of leads
SUSPICIOUS_AUC = 0.90      # single-feature AUC that triggers manual review

AVAILABILITY = [
    ("lead_source, industry, location, company_size", "At lead creation", "Safe"),
    ("salesperson_experience", "At lead assignment", "Safe"),
    ("response_time_hours", "After first response; fixed afterwards", "Safe (lead is scored after first response)"),
    ("lead_age_days, interactions, followups, website_visits",
     "Accumulate over time", "Conditionally safe: must be snapshotted at the scoring date. In a CRM export taken after close, lead age freezes at the close date and activity counts include post-decision activity, so they leak."),
    ("quotation_sent, quotation_value, demo_attended",
     "Mid-funnel events", "Conditionally safe: only events dated before the scoring date may be used."),
    ("previous_customer", "Before this lead", "Safe only if it means purchases made BEFORE this lead was created. If the CRM flag is updated when this lead converts, it encodes the target."),
    ("invoice_generated (demo only)", "After conversion", "LEAKY: exists only because the deal closed. Excluded."),
    ("Real-CRM fields to always exclude", "After outcome",
     "deal stage, close date, won/lost reason, contract signed, payment received, final deal amount"),
]


def build_pipeline(numeric, categorical):
    pre = ColumnTransformer([
        ("num", Pipeline([("imp", SimpleImputer(strategy="median")), ("sc", StandardScaler())]), numeric),
        ("cat", Pipeline([("imp", SimpleImputer(strategy="most_frequent")),
                          ("ohe", OneHotEncoder(handle_unknown="ignore"))]), categorical),
    ])
    return Pipeline([("pre", pre), ("clf", LogisticRegression(max_iter=2000))])


def single_feature_auc(X, y):
    results = []
    for col in X.columns:
        s = X[col]
        if pd.api.types.is_numeric_dtype(s):
            values = s.fillna(s.median())
        else:
            filled = s.fillna("__missing__")
            values = filled.map(y.groupby(filled).mean())
        auc = roc_auc_score(y, values)
        results.append((col, max(auc, 1 - auc)))
    return sorted(results, key=lambda r: r[1], reverse=True)


def main():
    meta = ru.load_metadata()
    features, X_train, _X_test, y_train, _y_test = ru.load_split(meta)

    rng = np.random.default_rng(ru.RANDOM_STATE)
    flip = rng.random(len(y_train)) < LEAK_NOISE
    X_leaky = X_train.copy()
    X_leaky[LEAKY] = np.where(flip, 1 - y_train.values, y_train.values)

    categorical = [c for c in features if not pd.api.types.is_numeric_dtype(X_train[c])]
    numeric = [c for c in features if c not in categorical]
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=ru.RANDOM_STATE)

    base = cross_val_score(build_pipeline(numeric, categorical), X_train, y_train, cv=cv, scoring="roc_auc")
    leak = cross_val_score(build_pipeline(numeric + [LEAKY], categorical), X_leaky, y_train, cv=cv, scoring="roc_auc")
    screen = single_feature_auc(X_leaky, y_train)
    flagged = [c for c, a in screen if a >= SUSPICIOUS_AUC]

    lines = [
        "# Leakage Analysis: Evidence",
        "",
        "Generated by `python src/leakage_demo.py`. Uses the **training split only**; the test set is not touched.",
        "",
        "## 1. Controlled leakage experiment",
        "",
        f"A deliberately leaky column `{LEAKY}` was added. It mimics a CRM field filled in only **after** a deal closes "
        f"(an invoice is raised only for converted leads). It matches the target for {100 * (1 - LEAK_NOISE):.0f}% of leads.",
        "",
        "| Feature set | 5-fold CV ROC-AUC (training split) |",
        "|---|---|",
        f"| Legitimate features only | {base.mean():.4f} ± {base.std():.4f} |",
        f"| Legitimate + `{LEAKY}` | {leak.mean():.4f} ± {leak.std():.4f} |",
        "",
        "The jump is what leakage looks like: near-perfect validation scores built on information that does not exist "
        "when a prediction is needed. That model would collapse in production.",
        "",
        "## 2. Detection: single-feature screen",
        "",
        f"Each feature's ROC-AUC on its own was computed on the training split (categoricals target-mean encoded). "
        f"Anything at or above {SUSPICIOUS_AUC:.2f} is flagged for manual timeline review. A high score is a reason to "
        "investigate, not proof of leakage: a genuinely strong predictor can also score high.",
        "",
        "| Feature | Single-feature AUC | Flag |",
        "|---|---|---|",
    ]
    lines += [f"| `{c}` | {a:.3f} | {'REVIEW' if a >= SUSPICIOUS_AUC else ''} |" for c, a in screen]
    lines += [
        "",
        f"Flagged: {', '.join(f'`{c}`' for c in flagged) if flagged else 'none'}. "
        f"Only the planted `{LEAKY}` should appear; it was removed. No legitimate feature was flagged."
        if flagged == [LEAKY] else
        f"Flagged: {', '.join(f'`{c}`' for c in flagged) if flagged else 'none'}. Review any legitimate feature listed here.",
        "",
        "## 3. Feature availability at prediction time",
        "",
        "| Feature(s) | When known | Leakage status |",
        "|---|---|---|",
    ]
    lines += [f"| {f} | {w} | {s} |" for f, w, s in AVAILABILITY]
    lines += [
        "",
        "## 4. Controls applied",
        "",
        "- The model scores leads at a defined point (mid-funnel, after first sales activity) using only values known at that date.",
        "- Train/test split happens before any fitted preprocessing; all imputation, scaling and encoding live inside the Pipeline.",
        "- The threshold is chosen from out-of-fold training predictions, never from the test set.",
        "- Any feature recorded after the outcome is excluded, and new features pass the single-feature screen above.",
        "- With real CRM data: build features from timestamped snapshots and use a time-based split (train on older leads, test on newer).",
        "",
    ]
    out = ru.REPORTS / "leakage_demo.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Baseline CV ROC-AUC: {base.mean():.4f}   With leak: {leak.mean():.4f}")
    print(f"Flagged by screen: {flagged}")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
