# Calibration analysis of the SAVED final model + cost-based threshold table.
# Does not retrain or modify the saved model.
import sys

import joblib
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from sklearn.base import clone
from sklearn.calibration import calibration_curve
from sklearn.metrics import brier_score_loss, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import StratifiedKFold, cross_val_predict

import review_utils as ru


def expected_calibration_error(y, p, bins=10):
    edges = np.linspace(0, 1, bins + 1)
    idx = np.clip(np.digitize(p, edges[1:-1]), 0, bins - 1)
    return sum((idx == b).mean() * abs(p[idx == b].mean() - y[idx == b].mean())
               for b in range(bins) if (idx == b).any())


def verdict(ece):
    if ece < 0.05:
        return "well calibrated"
    if ece < 0.10:
        return "moderately calibrated"
    return "poorly calibrated; consider CalibratedClassifierCV"


def main():
    meta = ru.load_metadata()
    threshold = ru.decision_threshold(meta)
    _features, X_train, X_test, y_train, y_test = ru.load_split(meta)
    pipe = joblib.load(ru.MODEL_PATH)

    p_test = pipe.predict_proba(X_test)[:, 1]
    auc = roc_auc_score(y_test, p_test)
    if abs(auc - ru.EXPECTED_TEST_AUC) > 0.0015:
        sys.exit(
            f"STOP: reproduced test ROC-AUC {auc:.4f} != expected {ru.EXPECTED_TEST_AUC}. "
            "The split in src/review_utils.py does not match src/train.py. "
            "Set TEST_SIZE / RANDOM_STATE there to the values used in train.py and re-run."
        )

    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=ru.RANDOM_STATE)
    p_oof = cross_val_predict(clone(pipe), X_train, y_train, cv=cv, method="predict_proba")[:, 1]

    yt, yo = np.asarray(y_test), np.asarray(y_train)
    base_rate = yo.mean()
    stats = {}
    for name, y, p in (("oof", yo, p_oof), ("test", yt, p_test)):
        brier = brier_score_loss(y, p)
        brier0 = np.mean((y - base_rate) ** 2)
        stats[name] = (brier, brier0, 1 - brier / brier0, expected_calibration_error(y, p))

    frac_pos, mean_pred = calibration_curve(yt, p_test, n_bins=10, strategy="quantile")
    oof_pos, oof_pred = calibration_curve(yo, p_oof, n_bins=10, strategy="quantile")

    ru.FIGURES.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(6, 6))
    ax.plot([0, 1], [0, 1], "--", color="grey", label="Perfect calibration")
    ax.plot(oof_pred, oof_pos, "o-", label="Out-of-fold (training)")
    ax.plot(mean_pred, frac_pos, "s-", label="Test set")
    ax.set_xlabel("Mean predicted probability")
    ax.set_ylabel("Actual conversion rate")
    ax.set_title("Calibration: final model")
    ax.legend()
    fig.tight_layout()
    fig_path = ru.FIGURES / "calibration_curve.png"
    fig.savefig(fig_path, dpi=120)
    plt.close(fig)

    ece_test = stats["test"][3]
    lines = [
        "# Calibration Analysis: Final Model",
        "",
        "Generated by `python src/calibration_analysis.py` from the saved pipeline (no retraining).",
        f"Sanity check: reproduced test ROC-AUC = {auc:.4f} (published: {ru.EXPECTED_TEST_AUC}).",
        "",
        "## What calibration means",
        "",
        "A model is calibrated if, among leads it scores at about 70%, about 70% actually convert. "
        "Ranking quality (ROC-AUC) and calibration are separate properties: a model can rank leads well "
        "and still output inflated or deflated probabilities.",
        "",
        "## Results",
        "",
        "| Metric | Out-of-fold (training) | Test |",
        "|---|---|---|",
        f"| Brier score (lower is better) | {stats['oof'][0]:.4f} | {stats['test'][0]:.4f} |",
        f"| Brier, base-rate-only baseline | {stats['oof'][1]:.4f} | {stats['test'][1]:.4f} |",
        f"| Brier skill score (higher is better) | {stats['oof'][2]:.3f} | {stats['test'][2]:.3f} |",
        f"| Expected calibration error (10 bins) | {stats['oof'][3]:.4f} | {stats['test'][3]:.4f} |",
        "",
        f"**Verdict:** on the test set the model is {verdict(ece_test)} (ECE {ece_test:.3f}). "
        "These numbers come from synthetic data and will drift with real behaviour.",
        "",
        "![Calibration curve](figures/calibration_curve.png)",
        "",
        "## Reliability table (test set, 10 equal-size bins)",
        "",
        "| Bin | Mean predicted | Actual conversion rate | Gap |",
        "|---|---|---|---|",
    ]
    lines += [f"| {i + 1} | {mp:.3f} | {fp:.3f} | {fp - mp:+.3f} |"
              for i, (mp, fp) in enumerate(zip(mean_pred, frac_pos))]
    lines += [
        "",
        "## Threshold under different business costs",
        "",
        "If probabilities are calibrated, the cost-minimising threshold is **t = 1 / (1 + r)**, where "
        "r = cost of missing a real buyer / cost of one wasted sales call. Values below use out-of-fold "
        "training predictions (the test set is not used for this choice).",
        "",
        "| r (miss : wasted call) | Threshold t | Recall | Precision | Leads flagged |",
        "|---|---|---|---|---|",
    ]
    for r in (1, 2, 3, 5, 10):
        t = 1 / (1 + r)
        pred = (p_oof >= t).astype(int)
        lines.append(
            f"| {r} : 1 | {t:.3f} | {recall_score(yo, pred, zero_division=0):.3f} | "
            f"{precision_score(yo, pred, zero_division=0):.3f} | {pred.mean():.1%} |"
        )
    lines += [
        "",
        f"The current threshold {threshold:.2f} (chosen by maximum F1) corresponds to r = {(1 - threshold) / threshold:.1f}, "
        "i.e. it assumes a missed buyer costs about that many times a wasted call. That ratio is an "
        "**assumption**; a real deployment should set it from actual deal value and sales capacity.",
        "",
    ]
    out = ru.REPORTS / "calibration_analysis.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Test ROC-AUC {auc:.4f} | Test Brier {stats['test'][0]:.4f} | Test ECE {ece_test:.4f} -> {verdict(ece_test)}")
    print(f"Wrote {out} and {fig_path}")


if __name__ == "__main__":
    main()
